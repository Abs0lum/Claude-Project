// Test stand-in for @minecraft/server, used only to LOAD BP-02 modules under Node for the pure-logic suites.
// Every event signal accepts subscribe/unsubscribe; scheduling calls return ids and never run.
// Any other property read on world/system/dimensions returns a harmless callable stub.

const signal = () => ({ subscribe: (fn) => fn, unsubscribe: () => {} });
const events = () => new Proxy({}, { get: () => signal() });

const stub = () => new Proxy(function () {}, {
  get: (t, k) => (k === Symbol.toPrimitive ? () => "" : k === "then" ? undefined : stub()),
  apply: () => undefined,
});

let nextId = 1;
const dyn = new Map();

export const system = new Proxy({
  afterEvents: events(),
  beforeEvents: events(),
  currentTick: 0,
  run: () => nextId++,
  runTimeout: () => nextId++,
  runInterval: () => nextId++,
  runJob: () => nextId++,
  clearRun: () => {},
  clearJob: () => {},
  waitTicks: () => Promise.resolve(),
}, { get: (t, k) => (k in t ? t[k] : stub()) });

export const world = new Proxy({
  afterEvents: events(),
  beforeEvents: events(),
  getDynamicProperty: (k) => dyn.get(k),
  setDynamicProperty: (k, v) => { if (v === undefined) dyn.delete(k); else dyn.set(k, v); },
  getDynamicPropertyIds: () => [...dyn.keys()],
  getAllPlayers: () => [],
  getPlayers: () => [],
  getTimeOfDay: () => 6000,
  getAbsoluteTime: () => 0,
  getDay: () => 0,
  sendMessage: () => {},
  getDimension: () => stub(),
}, { get: (t, k) => (k in t ? t[k] : stub()) });

