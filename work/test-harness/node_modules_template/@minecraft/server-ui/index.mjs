// Minimal test stand-in for @minecraft/server-ui (forms are never shown in unit tests).
class Form { constructor() { this._items = []; } title(t) { this._title = t; return this; } body(b) { this._body = b; return this; }
  button(...a) { this._items.push(["button", ...a]); return this; } button1(t) { this._b1 = t; return this; } button2(t) { this._b2 = t; return this; }
  textField(...a) { this._items.push(["text", ...a]); return this; } dropdown(...a) { this._items.push(["dropdown", ...a]); return this; }
  slider(...a) { this._items.push(["slider", ...a]); return this; } toggle(...a) { this._items.push(["toggle", ...a]); return this; }
  show() { return Promise.resolve({ canceled: true, cancelationReason: "UserClosed" }); } }
export class ActionFormData extends Form {}
export class MessageFormData extends Form {}
export class ModalFormData extends Form {}
export const FormCancelationReason = { UserBusy: "UserBusy", UserClosed: "UserClosed" };
